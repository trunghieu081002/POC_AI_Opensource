"""Everything about a pipeline-OWNED dbt project (`dbt_project:` in
pipeline.yaml, docs/hg-dbt-project.md) that must hold *before* it is trusted:
what its content is (for the approval hash), that all of it lives inside the
directory the pipeline is allowed to own, and that each stage's selectors
actually select models.

Pure file inspection + one `dbt ls` helper - no database, no dbt run. The
approval hash (approval.py), the loader's refusals, `validate` step 3 and the
runtime all use the same functions, so "what was approved", "what is allowed"
and "what is run" cannot drift apart: a run executes a private copy made by
`copy_project`, which copies exactly the files the hash covers.

The model for the hash is *everything in the project except generated
output*, not an allow-list of dbt's directory names: dbt executes SQL from
`analyses/`, `snapshots/`, `tests/`, `macros/`, `seeds/` and Python models
too, and a directory type added by a future dbt version would silently fall
outside an allow-list. A stray file that does nothing costs a re-review; a
missing executable one costs the approval its meaning.
"""
from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path, PurePosixPath

import yaml

# Generated by dbt itself, never authored: excluded from the approval hash
# and from the private copy a run is made from. These are *root-level*
# output directories (plus whatever `target-path`/`packages-install-path`/
# `log-path` redirect them to - see `output_roots`): a directory that merely
# shares the name deeper in the tree (`tests/logs/`) is authored content and
# stays covered. `package-lock.yml` is NOT here - it pins the package
# versions and is exactly what a reviewer approves.
DEFAULT_OUTPUT_ROOTS = frozenset({"target", "dbt_packages", "dbt_modules", "logs"})
_GENERATED_ROOT_FILES = frozenset({".user.yml"})
_GENERATED_ANYWHERE_FILES = frozenset({".DS_Store"})
_GENERATED_ANYWHERE_DIRS = frozenset({"__pycache__"})

# dbt_project.yml keys naming directories dbt reads from or writes to.
_PATH_LIST_KEYS = ("model-paths", "source-paths", "analysis-paths", "test-paths",
                   "seed-paths", "macro-paths", "snapshot-paths", "asset-paths",
                   "docs-paths", "clean-targets")
_PATH_SCALAR_KEYS = ("target-path", "packages-install-path", "log-path")
_SOURCE_DEFAULTS = {"model-paths": ["models"], "analysis-paths": ["analyses"],
                    "test-paths": ["tests"], "seed-paths": ["seeds"],
                    "macro-paths": ["macros"], "snapshot-paths": ["snapshots"]}


class DbtProjectError(Exception):
    pass


def _as_list(value) -> list:
    if value is None:
        return []
    return list(value) if isinstance(value, (list, tuple)) else [value]


def _rel_ok(value: str) -> bool:
    p = PurePosixPath(value)
    return bool(value) and not p.is_absolute() and ".." not in p.parts and not value.startswith("~")


def _config(project: Path) -> dict:
    try:
        cfg = yaml.safe_load((Path(project) / "dbt_project.yml").read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as exc:
        raise DbtProjectError(f"dbt_project.yml is not valid YAML: {exc}") from None
    except OSError as exc:
        raise DbtProjectError(f"cannot read dbt_project.yml: {exc}") from None
    if not isinstance(cfg, dict):
        raise DbtProjectError("dbt_project.yml must be a mapping")
    return cfg


def output_roots(project: Path) -> frozenset[str]:
    """Top-level names under `project` that are dbt output, not authored
    content: the defaults plus wherever the project redirected its output."""
    roots = set(DEFAULT_OUTPUT_ROOTS)
    cfg = _config(project)
    for key in _PATH_SCALAR_KEYS:
        value = cfg.get(key)
        if isinstance(value, str) and _rel_ok(value):
            roots.add(PurePosixPath(value).parts[0])
    return frozenset(roots)


def _walk(project: Path, roots: frozenset[str]):
    """(relative PurePosixPath, absolute Path) for every authored entry under
    `project`. Symlinks are listed (never followed) so the caller can refuse
    them."""
    project = Path(project)
    for dirpath, dirnames, filenames in os.walk(project, followlinks=False):
        here = Path(dirpath)
        at_root = here == project
        rel_dir = PurePosixPath(here.relative_to(project).as_posix())
        keep = []
        for d in sorted(dirnames):
            rel = PurePosixPath(d) if at_root else rel_dir / d
            if (at_root and d in roots) or d in _GENERATED_ANYWHERE_DIRS:
                continue
            if (here / d).is_symlink():
                yield rel, here / d            # listed, not descended into
            else:
                keep.append(d)
        dirnames[:] = keep
        for f in sorted(filenames):
            if (at_root and f in _GENERATED_ROOT_FILES) or f in _GENERATED_ANYWHERE_FILES:
                continue
            yield (PurePosixPath(f) if at_root else rel_dir / f), here / f


def project_files(project: Path) -> list[tuple[str, bytes]]:
    """(path relative to `project`, raw bytes) of every authored file, sorted -
    exactly what the approval hash covers. Raises DbtProjectError on a
    symlink: hashing a link's target would hash content that lives outside
    the project and can change without any file in it changing."""
    project = Path(project)
    out = []
    for rel, path in _walk(project, output_roots(project)):
        if path.is_symlink():
            raise DbtProjectError(f"{rel} is a symlink - refused (see check_project)")
        out.append((rel.as_posix(), path.read_bytes()))
    return sorted(out)


def copy_project(project: Path, dest: Path) -> int:
    """Copies exactly the files `project_files` hashes into `dest` and
    nothing else - so what a run executes is, file for file, what the
    approval covered, and generated output (`target/`, a stale
    `dbt_packages/`, `logs/`) never comes along. Returns the file count."""
    Path(dest).mkdir(parents=True, exist_ok=True)
    n = 0
    for rel, _ in project_files(project):
        target = Path(dest) / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(Path(project) / rel, target)
        n += 1
    return n


def _paths_for(project: Path, key: str) -> list[Path]:
    """The directories a dbt_project.yml key names (default if unset), as
    paths under `project` - `seed-paths: [data/seeds]` is a real setting, and
    code that assumed a literal `seeds/` would skip those seeds and let
    models read an empty or missing table."""
    cfg = _config(project)
    values = [v for v in _as_list(cfg.get(key)) if isinstance(v, str) and _rel_ok(v)]
    return [Path(project) / v for v in (values or _SOURCE_DEFAULTS.get(key, []))]


def has_seeds(project: Path) -> bool:
    return any(d.is_dir() and any(d.rglob("*.csv")) for d in _paths_for(project, "seed-paths"))


def count_models(project: Path) -> int:
    return sum(1 for d in _paths_for(project, "model-paths") if d.is_dir() for _ in d.rglob("*.sql"))


def check_project(project: Path) -> None:
    """Refuses a project that reaches outside the directory it is allowed to
    own, or whose content the approval hash cannot see. Raises
    DbtProjectError naming exactly what and where.

    - **Symlinks** anywhere in the project (files or directories): a link's
      content lives elsewhere, is not in the hash, and `shutil.copytree`
      would follow it when the pipeline is published.
    - **Path settings** in dbt_project.yml (`model-paths`, `macro-paths`,
      `seed-paths`, `target-path`, `packages-install-path`, ...) that are
      absolute or contain `..`: dbt would read or write outside the project.
    - **Output redirected onto authored content** (`target-path: macros`):
      the macros would count as generated output and drop out of the hash.
    - **Local packages** (`local:` in packages.yml / dependencies.yml) that
      are absolute or resolve outside the project: their files are not in
      the project, so not in the hash. A local package *inside* the project
      is just more project files and is covered.
    - **Unpinned remote packages**: any non-local package requires a
      `package-lock.yml`, because the hash covers the lock - without one a
      version range resolves to whatever is newest on the day of the run.
    """
    project = Path(project)
    root = project.resolve()
    roots = output_roots(project)
    for rel, path in _walk(project, roots):
        if path.is_symlink():
            raise DbtProjectError(
                f"{rel} is a symlink (-> {os.readlink(path)}) - a dbt project may not "
                f"contain symlinks: the target is outside what the approval hash covers")
        try:
            path.resolve().relative_to(root)
        except ValueError:
            raise DbtProjectError(f"{rel} resolves outside the project") from None

    cfg = _config(project)
    for key in _PATH_LIST_KEYS:
        for value in _as_list(cfg.get(key)):
            if not isinstance(value, str) or not _rel_ok(value):
                raise DbtProjectError(
                    f"dbt_project.yml {key}: {value!r} must be a relative path inside "
                    f"the project (no absolute path, no '..')")
    for key in _PATH_SCALAR_KEYS:
        value = cfg.get(key)
        if value is not None and (not isinstance(value, str) or not _rel_ok(value)):
            raise DbtProjectError(
                f"dbt_project.yml {key}: {value!r} must be a relative path inside the project")
    for key, defaults in _SOURCE_DEFAULTS.items():
        for value in (_as_list(cfg.get(key)) or defaults):
            if isinstance(value, str) and _rel_ok(value) \
                    and PurePosixPath(value).parts[0] in roots:
                raise DbtProjectError(
                    f"dbt_project.yml {key}: {value!r} sits inside a directory the project "
                    f"also uses for generated output ({sorted(roots)}) - authored files there "
                    f"would be excluded from the approval hash")

    has_remote = False
    for fname in ("packages.yml", "dependencies.yml"):
        f = project / fname
        if not f.exists():
            continue
        try:
            doc = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        except yaml.YAMLError as exc:
            raise DbtProjectError(f"{fname} is not valid YAML: {exc}") from None
        for entry in _as_list(doc.get("packages") if isinstance(doc, dict) else None):
            if not isinstance(entry, dict):
                raise DbtProjectError(f"{fname}: every package must be a mapping, got {entry!r}")
            if "local" in entry:
                local = entry["local"]
                if not isinstance(local, str) or not local:
                    raise DbtProjectError(f"{fname}: a local package path must be a string")
                if PurePosixPath(local).is_absolute():
                    raise DbtProjectError(f"{fname}: local package {local!r} is an absolute path")
                try:
                    (project / local).resolve().relative_to(root)
                except ValueError:
                    raise DbtProjectError(
                        f"{fname}: local package {local!r} resolves outside the project - "
                        f"its files would not be covered by the approval hash") from None
            else:
                has_remote = True
    if has_remote and not (project / "package-lock.yml").exists():
        raise DbtProjectError(
            "packages.yml lists remote packages but there is no package-lock.yml - without "
            "it a version range resolves to whatever is newest on the day of the run, which "
            "no approval can pin. Run `dbt deps` once and commit the lock")


# ------------------------------------------------------------ selectors

def list_selected_models(dbt_bin: str, base_args: list[str], selector: str,
                         *, timeout: int = 120) -> list[str]:
    """Names of the models `selector` selects, via `dbt ls`. `dbt ls` (and
    `dbt run`) exit 0 and select NOTHING for a selector that matches no node
    ("The selection criterion 'x' does not match any enabled nodes", then
    "Nothing to do") - so the exit code says nothing here; the caller must
    treat an empty list as the failure it is. A nonzero exit (a real parse
    error) raises DbtProjectError with dbt's own message."""
    try:
        proc = subprocess.run(
            [dbt_bin, "ls", "--select", selector, "--resource-type", "model",
             "--output", "name", "--quiet", *base_args],
            capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        raise DbtProjectError(f"dbt ls --select {selector!r} timed out after {timeout}s") from None
    if proc.returncode != 0:
        raise DbtProjectError(
            f"dbt ls --select {selector!r} failed:\n{(proc.stderr or proc.stdout).strip()[-2000:]}")
    return [line.strip() for line in proc.stdout.splitlines() if line.strip()]


def stage_models(dbt_bin: str, base_args: list[str], stage) -> tuple[list[str], list[str]]:
    """(the models a dbt stage's selectors select, the problems). Every
    selector must select at least one model - checked per selector, not per
    stage: a stage `[dim_artist, dim_artsit]` whose typo selects nothing
    would otherwise run the one that matched and report success for a stage
    the manifest claims builds two things."""
    models: list[str] = []
    problems: list[str] = []
    for selector in stage.models:
        try:
            selected = list_selected_models(dbt_bin, base_args, selector)
        except DbtProjectError as exc:
            problems.append(f"stage {stage.name!r}: {exc}")
            continue
        if not selected:
            problems.append(
                f"stage {stage.name!r}: selector {selector!r} selects 0 models "
                f"(dbt would exit 0 with 'Nothing to do' and the stage would look "
                f"successful) - fix the selector or the project")
        models.extend(m for m in selected if m not in models)
    return models, problems


def check_selectors(dbt_bin: str, base_args: list[str], stages: list) -> list[str]:
    """For every selector of every dbt stage: it must select at least one
    model. Returns the problems (empty = fine)."""
    problems = []
    for stage in stages:
        problems.extend(stage_models(dbt_bin, base_args, stage)[1])
    return problems


# ------------------------------------------------------------ dbt test verdict

# A `dbt test` outcome is one of these - never inferred from the exit code, and never "passed"
# because nothing said otherwise:
#   passed          every test the manifest attaches to the stage's models ran and passed (a
#                   `severity: warn` test that found rows counts as dbt says: warned, not failed),
#                   and every one of those models has at least one test
#   failed          a test failed or errored, a test the manifest requires did not run or was
#                   skipped, or dbt exited non-zero                                 -> stage fails
#   error           run_results.json / manifest.json missing or unreadable: nothing is known
#                   about the tests, which is not the same as "no tests"           -> stage fails
#   not_applicable  the stage's models have no tests at all                         -> stage runs,
#   incomplete      some of the stage's models have no tests                           A2 refuses
TEST_STAGE_FAILS = frozenset({"failed", "error"})
TEST_RECORD_LIMIT = 1000


def _read_json(path: Path, what: str) -> tuple[dict | None, str]:
    import json
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None, f"dbt test wrote no {what}"
    except (OSError, ValueError) as exc:
        return None, f"dbt test's {what} is unreadable: {exc}"
    if not isinstance(data, dict):
        return None, f"dbt test's {what} is not a JSON object"
    return data, ""


def dbt_test_verdict(run_results: Path, manifest: Path, models: list[str], *, exit_code: int) -> dict:
    """What one stage's `dbt test` proved, from dbt's own artifacts: `run_results.json` (what
    ran, how it ended) checked against `manifest.json` (which tests exist on the models the
    stage built - `models`, from `stage_models`). The required set comes from the manifest, not
    from what happened to run, so a selector or an indirect-selection mode that leaves a test
    out is caught, as is a skipped test."""
    out = {"status": "error", "reason": "", "exit_code": exit_code, "models": list(models),
           "ran": 0, "passed": 0, "failed": 0, "errored": 0, "warned": 0, "skipped": 0,
           "required": [], "missing": [], "untested_models": [], "failing": [], "tests": []}
    results, problem = _read_json(run_results, "run_results.json")
    if results is not None and not isinstance(results.get("results"), list):
        results, problem = None, "dbt test's run_results.json has no results list"
    man, man_problem = _read_json(manifest, "manifest.json")
    if man is not None and not isinstance(man.get("nodes"), dict):
        man, man_problem = None, "dbt test's manifest.json has no nodes"
    if results is None or man is None:
        out["reason"] = "; ".join(p for p in (problem, man_problem) if p)
        return out

    nodes = man["nodes"]
    model_ids = {uid for uid, n in nodes.items()
                 if isinstance(n, dict) and n.get("resource_type") == "model"
                 and n.get("name") in models}
    tested: set[str] = set()
    required = []
    for uid, n in sorted(nodes.items()):
        if not isinstance(n, dict) or n.get("resource_type") != "test":
            continue
        on = set((n.get("depends_on") or {}).get("nodes") or []) & model_ids
        if on:
            required.append(uid)
            tested |= on
    out["required"] = required
    out["untested_models"] = sorted(n for n in models
                                    if not any(nodes[u].get("name") == n for u in tested))

    seen: dict[str, str] = {}
    for r in results["results"]:
        uid = str((r or {}).get("unique_id", "")) if isinstance(r, dict) else ""
        if not uid.startswith("test."):
            continue
        status = str(r.get("status", ""))
        seen[uid] = status
        out["ran"] += 1
        key = {"pass": "passed", "fail": "failed", "error": "errored", "warn": "warned",
               "skipped": "skipped"}.get(status, "errored")
        out[key] += 1
        node = nodes.get(uid) if isinstance(nodes.get(uid), dict) else {}
        meta = node.get("test_metadata") or {}
        on = [nodes[m].get("name") for m in (node.get("depends_on") or {}).get("nodes") or []
              if isinstance(nodes.get(m), dict) and nodes[m].get("resource_type") == "model"]
        # what the test IS, from dbt's manifest - lets a policy ask "is there a unique test on this
        # column of this model, failing the run (severity error)?" without trusting any YAML text
        out["tests"].append({"test": uid, "status": status, "failures": r.get("failures"),
                             "name": meta.get("name"),
                             "column": (meta.get("kwargs") or {}).get("column_name"),
                             "models": on,
                             "severity": str((node.get("config") or {}).get("severity") or "").lower()})
        if key in ("failed", "errored", "skipped"):
            out["failing"].append(f"{uid} {status}"
                                  + (f" ({r.get('failures')} failing row(s))" if r.get("failures") else ""))
    out["missing"] = [u for u in required if u not in seen]

    if out["failed"] or out["errored"]:
        out["status"], out["reason"] = "failed", "a test failed or errored"
    elif out["missing"]:
        out["status"] = "failed"
        out["reason"] = (f"{len(out['missing'])} test(s) the manifest attaches to "
                         f"{models} did not run: {', '.join(out['missing'][:10])}")
    elif any(seen.get(u) == "skipped" for u in required):
        out["status"], out["reason"] = "failed", "a required test was skipped"
    elif exit_code != 0:
        out["status"], out["reason"] = "failed", f"dbt test exited {exit_code}"
    elif not required:
        out["status"], out["reason"] = "not_applicable", f"no dbt tests are declared on {models}"
    elif out["untested_models"]:
        out["status"] = "incomplete"
        out["reason"] = f"model(s) with no dbt test: {', '.join(out['untested_models'])}"
    else:
        out["status"] = "passed"
    return out


def dbt_test_record_problems(data: dict) -> list[str]:
    """The A2 gate's own re-check of a recorded verdict (the event's data, not its name):
    `passed` must be backed by the raw per-test results it carries."""
    status = data.get("status")
    if status != "passed":
        return [f"dbt test is {status or 'unrecorded'!r}"
                + (f": {data.get('reason')}" if data.get("reason") else "")]
    problems = []
    tests = data.get("tests")
    required = data.get("required")
    if not isinstance(tests, list) or not isinstance(required, list) or data.get("truncated"):
        return ["the dbt test record does not carry its per-test results"]
    by_id = {t.get("test"): t.get("status") for t in tests if isinstance(t, dict)}
    if not required:
        problems.append("no required dbt test on record")
    for uid in required:
        if by_id.get(uid) not in ("pass", "warn"):
            problems.append(f"required test {uid} is {by_id.get(uid) or 'not run'!r}")
    bad = [u for u, s in by_id.items() if s not in ("pass", "warn")]
    if bad:
        problems.append(f"test(s) not passed: {', '.join(bad[:10])}")
    if data.get("untested_models"):
        problems.append(f"model(s) with no dbt test: {data['untested_models']}")
    if data.get("exit_code") != 0:
        problems.append(f"dbt test exited {data.get('exit_code')}")
    return problems


def required_test_problems(tests: list[dict], required: list[dict]) -> list[str]:
    """Acceptance policy on top of the verdict: each `{model, column, tests: [...], severity}` in
    `required` (expected.yaml's `required_dbt_tests`, never the draft's own YAML) must be among the
    tests dbt RAN (`tests` = the per-test entries of a verdict, as dbt's manifest describes them),
    with that severity, and have passed."""
    problems = []
    for req in required:
        sev = str(req.get("severity") or "error").lower()
        for name in req["tests"]:
            want = f"a `{name}` test on {req['model']}.{req['column']}"
            hits = [t for t in tests if t.get("name") == name and t.get("column") == req["column"]
                    and req["model"] in (t.get("models") or [])]
            if not hits:
                problems.append(f"required {want}: dbt ran none")
            elif not any(t.get("severity") == sev for t in hits):
                problems.append(f"required {want} has severity "
                                f"{sorted({str(t.get('severity')) for t in hits})}; required {sev!r}")
            elif not any(t.get("severity") == sev and t.get("status") == "pass" for t in hits):
                problems.append(f"required {want} did not pass")
    return problems


def parse_required_tests(raw, where: str) -> list[dict]:
    if raw is None:
        return []
    if not isinstance(raw, list):
        raise ValueError(f"{where}: required_dbt_tests must be a list")
    out = []
    for i, req in enumerate(raw):
        if not (isinstance(req, dict) and isinstance(req.get("model"), str) and req["model"]
                and isinstance(req.get("column"), str) and req["column"]
                and isinstance(req.get("tests"), list) and req["tests"]
                and all(isinstance(t, str) and t for t in req["tests"])
                and str(req.get("severity", "error")).lower() in ("error", "warn")
                and set(req) <= {"model", "column", "tests", "severity"}):
            raise ValueError(f"{where}: required_dbt_tests[{i}] needs model, column, tests "
                             f"(and optionally severity: error|warn), nothing else")
        out.append({"model": req["model"], "column": req["column"], "tests": list(req["tests"]),
                    "severity": str(req.get("severity", "error")).lower()})
    return out

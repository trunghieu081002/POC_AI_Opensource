"""The 3-layer demo (docs/demo.md, examples/demo/), offline: it never approves by itself, its specs hold no secret,
the hand-written reference pipeline is labelled and meets the case's required gates and schedule, the hand-written
dashboard states the same numbers as the case's expected result, and the runner refuses an AI demo without a model."""
import importlib.util
import os
import re
import subprocess
from decimal import Decimal
from pathlib import Path

import yaml

from dpagent.pipelines import fixture, loader

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "examples" / "demo"
CASE = ROOT / "tests" / "llm_verification" / "cases" / "fulfilment_sla"


def test_the_demo_never_approves_by_itself():
    demo = (D / "demo.sh").read_text()
    approve = demo[demo.index("  approve)"):demo.index("  deploy)")]
    assert "need DEMO_APPROVED_BY" in approve and '--approved-by "$DEMO_APPROVED_BY"' in approve
    bi = demo[demo.index("  bi-deploy)"):demo.index("  bad-data)")]
    assert "need DEMO_BI_APPROVED_BY DEMO_BI_APPROVED_SHA256" in bi
    assert "promote" not in demo[demo.index("  synth)"):demo.index("  validate)")]   # drafting never promotes
    env = (D / "dev.env.example").read_text()
    assert re.search(r"^DEMO_APPROVED_BY=$", env, re.M) and re.search(r"^DEMO_BI_APPROVED_BY=$", env, re.M)


def test_specs_hold_only_environment_references():
    for spec in ("stack.yaml", "bi.yaml"):
        text = (D / spec).read_text()
        for line in text.splitlines():
            if re.search(r"(password|secret_key)\s*:", line):
                assert "${" in line, line
    values = dict(l.split("=", 1) for l in (D / "dev.env.example").read_text().splitlines()
                  if l and not l.startswith("#"))
    assert all(v in ("", "change-me", "change-me-viewer", "change-me-to-at-least-32-random-characters")
               for k, v in values.items() if "PASSWORD" in k or "SECRET" in k)


def test_the_reference_is_labelled_and_meets_the_cases_contract(tmp_path):
    ref = D / "reference" / "fulfilment_sla"
    assert "NOT drafted by AI" in (ref / "ORIGIN.md").read_text()
    assert "Hand-written reference" in (ref / "pipeline.yaml").read_text()
    pipeline = loader.load("fulfilment_sla", D / "reference")
    expected = fixture.load_expected(CASE / "expected.yaml")
    assert fixture.required_gate_problems(pipeline, expected.required_gates) == []
    assert pipeline.schedule == "0 2 * * *"                       # brd.md "Vận hành": daily 02:00 UTC
    assert pipeline.warehouse.schema == "fulfilment_sla"
    sql = (ref / "models" / "fct_delivery_sla.sql").read_text()
    assert "fulfilment_sla_landing.sale_order" in sql and "fulfilment_sla_landing.stock_picking" in sql


def test_the_ai_draft_gets_the_same_names_the_reference_uses():
    demo = (D / "demo.sh").read_text()
    for ref in ("FS_SRC_HOST", "FS_SRC_PORT", "FS_SRC_NAME", "FS_SRC_USER", "FS_SRC_PASSWORD"):
        assert f'--secret "{ref}=' in demo and f"${{{ref}}}" in (D / "reference/fulfilment_sla/pipeline.yaml").read_text()
    assert "--fixture" in demo and "--max-calls" in demo and "--max-revisions" in demo


def test_the_dashboard_states_the_cases_numbers_and_is_labelled_hand_written():
    bi = yaml.safe_load((ROOT / "projects/fulfil-sla/expected.yaml").read_text())["checks"][0]
    case = yaml.safe_load((CASE / "expected.yaml").read_text())["rows"]
    norm = lambda rows: sorted((r["month"], r["eligible_orders"], r["delivered_orders"], r["on_time_orders"],
                                Decimal(str(r["on_time_rate"]))) for r in rows)
    assert norm(bi["rows"]) == norm(case)
    assert norm(bi["filters"][0]["rows"]) == norm([r for r in case if r["month"] == "2026-02"])
    assert "NOT generated by AI" in (ROOT / "projects/fulfil-sla/expected.yaml").read_text()
    assert "HAND-WRITTEN" in (D / "bi.yaml").read_text()


def test_the_dashboard_bundle_is_valid_and_owns_its_own_uuids():
    spec = importlib.util.spec_from_file_location("assets_demo", ROOT / "packs/superset-assets/assets.py")
    a = importlib.util.module_from_spec(spec); spec.loader.exec_module(a)
    cwd = os.getcwd(); os.chdir(ROOT)
    try:
        def read(name, **extra):
            return a.read_project({"name": name, "revision": "v1", "bundle_dir": f"projects/{name}/bundle",
                                   "expected_file": f"projects/{name}/expected.yaml", **extra}, {"environment": "dev"})
        mine = read("fulfil-sla", viewers=[{"username": "fulfil.viewer", "password_env": "FS_VIEWER_PASSWORD"}])
        others = [read(n) for n in ("quickstart-sales", "quickstart-ops")]
    finally:
        os.chdir(cwd)
    keys = lambda p: {k for v in p["resources"].values() for k in v}
    assert all(not keys(mine) & keys(o) for o in others)


def test_an_ai_demo_without_a_model_is_refused_before_anything_is_built():
    env = {k: v for k, v in os.environ.items() if k not in ("DPAGENT_MODEL", "GEMINI_API_KEY")}
    r = subprocess.run(["bash", str(ROOT / "scripts/quickstart-acceptance-ci.sh"), "--demo", "ai"],
                       env=env, capture_output=True, text=True, timeout=60)
    assert r.returncode == 2 and "needs DPAGENT_MODEL" in r.stderr


